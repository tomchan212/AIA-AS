export type MessageKey = keyof typeof zh;

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const template = (locale === "en" ? en : zh)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function layerLabel(locale: Locale, id: LayerId) {
  const key = { protection: "protection", stable: "stableLayer", growth: "growthLayer", speculative: "speculativeLayer" } as const;
  return t(locale, key[id]);
}

export function statusLabel(locale: Locale, status: GapStatus) {
  return t(locale, status);
}

export function profileLabel(locale: Locale, profile: RiskProfile) {
  const key = { conservative: "conservative", stable: "stableProfile", balanced: "balancedProfile", growth: "growthProfile" } as const;
  return t(locale, key[profile]);
}

export function reasonAction(locale: Locale, reason: ReasonCode) {
  return t(locale, `action_${reason}`);
}
